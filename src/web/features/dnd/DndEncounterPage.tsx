import { useEffect, useRef, useState } from "react";
import { useTranslation } from "react-i18next";
import { AlertTriangle, Dices, Plus, RefreshCw, Swords } from "lucide-react";

import { createDndState, makeDndCombatant } from "../../../systems/dnd5e/combat";
import {
  DND_DIFFICULTIES,
  formatCr,
  generateDndEncounter,
  type DndDifficulty,
  type DndEncounterPlan,
} from "../../../systems/dnd5e/encounter";
import { db } from "../../db";
import { useAllMonsters } from "../../hooks/useLibrary";
import { useApp } from "../../store";

const THEME_CHIPS = [
  "undead",
  "goblin",
  "dragon",
  "beast",
  "humanoid",
  "giant",
];

function defaultHp(cr: number): number {
  return Math.max(4, Math.round(8 + cr * 14));
}

function defaultAc(cr: number): number {
  return Math.round(12 + cr / 2);
}

export function DndEncounterPage() {
  const { t } = useTranslation();
  const monsters = useAllMonsters();
  const setTab = useApp((state) => state.setTab);
  const setActiveEncounterId = useApp((state) => state.setActiveEncounterId);

  const [partyLevel, setPartyLevel] = useState(1);
  const [partySize, setPartySize] = useState(4);
  const [difficulty, setDifficulty] = useState<DndDifficulty>("medium");
  const [theme, setTheme] = useState("");
  const [maxCreatures, setMaxCreatures] = useState(8);
  const [seed, setSeed] = useState("");
  const [plan, setPlan] = useState<DndEncounterPlan | null>(null);
  const [adding, setAdding] = useState(false);
  const autoGenerated = useRef(false);

  const generate = (nextSeed = seed) => {
    const themes = theme
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean);
    setPlan(
      generateDndEncounter({
        partyLevel,
        partySize,
        difficulty,
        theme: themes,
        maxCreatures,
        seed: nextSeed.trim() ? Number(nextSeed) : undefined,
        pool: monsters,
      }),
    );
  };

  useEffect(() => {
    if (autoGenerated.current || monsters.length === 0) return;
    autoGenerated.current = true;
    setPlan(
      generateDndEncounter({
        partyLevel: 1,
        partySize: 4,
        difficulty: "medium",
        pool: monsters,
      }),
    );
  }, [monsters]);

  const reroll = () => {
    const next = String(Math.floor(Math.random() * 1_000_000));
    setSeed(next);
    generate(next);
  };

  const toggleTheme = (value: string) => {
    const current = theme
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean);
    const next = current.includes(value)
      ? current.filter((item) => item !== value)
      : [...current, value];
    setTheme(next.join(", "));
  };

  const addToCombat = async () => {
    if (!plan || !plan.groups.length) return;
    setAdding(true);
    try {
      const state = createDndState();
      for (const group of plan.groups) {
        for (let index = 0; index < group.count; index++) {
          const monster = group.monster;
          state.combatants.push(
            makeDndCombatant({
              name:
                group.count > 1
                  ? `${monster.name} ${index + 1}`
                  : monster.name,
              kind: "npc",
              level: monster.level,
              cr: formatCr(monster.level),
              maxHp: monster.hp ?? defaultHp(monster.level),
              ac: monster.ac ?? defaultAc(monster.level),
              initiative: null,
              initiativeMod: monster.initiativeMod ?? 0,
            }),
          );
        }
      }

      const id = crypto.randomUUID();
      const now = Date.now();
      await db.encounters.add({
        id,
        systemId: "dnd5e",
        name: `${t(`dnd.difficulty.${plan.difficulty}`)} · ур. ${plan.partyLevel}`,
        state,
        createdAt: now,
        updatedAt: now,
      });

      setActiveEncounterId(id);
      setTab("combat");
    } finally {
      setAdding(false);
    }
  };

  const activeThemes = theme
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);

  return (
    <div className="fade-in">
      <header className="page-head">
        <div>
          <h1 className="page-title">{t("encounter.title")}</h1>
          <p className="page-sub">{t("dnd.encounterSubtitle")}</p>
        </div>
        {plan && (
          <span className="badge badge-gold">
            {t("encounter.threat")}: {t(`dnd.difficulty.${plan.threat}`)}
          </span>
        )}
      </header>

      <div className="encounter-grid">
        <section className="panel panel-pad space-y-4">
          <div className="grid grid-cols-2 gap-3">
            <label className="field">
              <span className="label">{t("encounter.partyLevel")}</span>
              <input
                className="input num"
                type="number"
                min={1}
                max={20}
                value={partyLevel}
                onChange={(event) => setPartyLevel(Number(event.target.value))}
              />
            </label>
            <label className="field">
              <span className="label">{t("encounter.partySize")}</span>
              <input
                className="input num"
                type="number"
                min={1}
                max={10}
                value={partySize}
                onChange={(event) => setPartySize(Number(event.target.value))}
              />
            </label>
          </div>

          <div className="field">
            <span className="label">{t("encounter.difficulty")}</span>
            <div className="flex flex-wrap gap-1.5">
              {DND_DIFFICULTIES.map((value) => (
                <button
                  key={value}
                  type="button"
                  className={`chip ${difficulty === value ? "on" : ""}`}
                  onClick={() => setDifficulty(value)}
                >
                  {t(`dnd.difficulty.${value}`)}
                </button>
              ))}
            </div>
          </div>

          <label className="field">
            <span className="label">{t("encounter.theme")}</span>
            <input
              className="input"
              value={theme}
              onChange={(event) => setTheme(event.target.value)}
              placeholder={t("encounter.themePlaceholder")}
            />
            <span className="faint text-[11px]">{t("encounter.themeHint")}</span>
          </label>

          <div className="flex flex-wrap gap-1.5">
            {THEME_CHIPS.map((value) => (
              <button
                key={value}
                type="button"
                className={`chip ${activeThemes.includes(value) ? "on" : ""}`}
                onClick={() => toggleTheme(value)}
              >
                {value}
              </button>
            ))}
          </div>

          <div className="grid grid-cols-2 gap-3">
            <label className="field">
              <span className="label">{t("encounter.maxCreatures")}</span>
              <input
                className="input num"
                type="number"
                min={1}
                max={16}
                value={maxCreatures}
                onChange={(event) =>
                  setMaxCreatures(Number(event.target.value))
                }
              />
            </label>
            <label className="field">
              <span className="label">{t("encounter.seed")}</span>
              <input
                className="input num"
                value={seed}
                onChange={(event) => setSeed(event.target.value)}
                placeholder="42"
                title={t("encounter.seedHint")}
              />
            </label>
          </div>
          <p className="faint text-[11px]">{t("encounter.seedHint")}</p>

          <div className="flex gap-2">
            <button
              type="button"
              className="btn btn-primary flex-1"
              onClick={() => generate()}
              disabled={!monsters.length}
            >
              <Dices size={15} />
              {t("encounter.generate")}
            </button>
            <button
              type="button"
              className="btn"
              onClick={reroll}
              disabled={!monsters.length}
              title={t("encounter.reroll")}
            >
              <RefreshCw size={15} />
            </button>
          </div>

          {!monsters.length && (
            <p className="text-xs red">{t("encounter.noPool")}</p>
          )}
        </section>

        <section className="panel overflow-hidden">
          {plan && plan.groups.length ? (
            <>
              <div className="panel-pad pb-4">
                <div className="flex items-end justify-between gap-4">
                  <div>
                    <div className="label">{t("encounter.budget")}</div>
                    <div className="num text-2xl">
                      {plan.spent}{" "}
                      <span className="faint text-sm">/ {plan.budget} XP</span>
                    </div>
                  </div>
                  <div className="text-right">
                    <div className="label">{t("encounter.perPc")}</div>
                    <div className="num text-lg gold">
                      {plan.awardedXp} XP
                    </div>
                  </div>
                </div>

                <div className="budget-bar mt-3">
                  <div
                    className="budget-fill"
                    style={{
                      width: `${Math.min(
                        100,
                        (plan.spent / plan.budget) * 100,
                      )}%`,
                    }}
                  />
                </div>

                <div className="mt-2 flex flex-wrap gap-3 text-xs muted">
                  <span>
                    {t("encounter.total")}:{" "}
                    <b className="text-[var(--text)]">{plan.totalCount}</b>
                  </span>
                  <span>
                    {t("dnd.baseXp")}:{" "}
                    <b className="text-[var(--text)]">{plan.baseXp}</b>
                  </span>
                  <span>
                    {t("dnd.multiplier")}:{" "}
                    <b className="text-[var(--text)]">×{plan.multiplier}</b>
                  </span>
                  <span>
                    {t("encounter.threat")}:{" "}
                    <b className="text-[var(--text)]">
                      {t(`dnd.difficulty.${plan.threat}`)}
                    </b>
                  </span>
                </div>
              </div>

              <div
                className="border-t"
                style={{ borderColor: "var(--border-soft)" }}
              >
                {plan.groups.map((group) => (
                  <div
                    key={`${group.monster.id ?? group.monster.name}`}
                    className="group-row"
                  >
                    <span className="group-count">{group.count}×</span>
                    <div className="min-w-0 flex-1">
                      <div className="truncate font-medium">
                        {group.monster.name}
                      </div>
                      <div className="text-xs muted">
                        CR {formatCr(group.monster.level)}
                        {group.monster.traits?.length
                          ? ` · ${group.monster.traits.slice(0, 2).join(", ")}`
                          : ""}
                      </div>
                    </div>
                    <div className="text-right">
                      <div className="num text-sm">
                        {group.xpEach} XP × {group.count}
                      </div>
                      <div className="faint text-[11px]">
                        {group.subtotal} XP
                      </div>
                    </div>
                  </div>
                ))}
              </div>

              <div
                className="panel-pad space-y-3 border-t"
                style={{ borderColor: "var(--border-soft)" }}
              >
                {plan.warnings.length > 0 && (
                  <div className="space-y-1.5">
                    {plan.warnings.map((warning) => (
                      <div
                        key={warning}
                        className="flex items-start gap-2 text-xs"
                        style={{ color: "#d9b26a" }}
                      >
                        <AlertTriangle size={13} className="mt-0.5 flex-none" />
                        <span>{warning}</span>
                      </div>
                    ))}
                  </div>
                )}

                <div className="flex gap-2">
                  <button
                    type="button"
                    className="btn btn-gold flex-1"
                    onClick={() => void addToCombat()}
                    disabled={adding}
                  >
                    <Swords size={15} />
                    {t("encounter.addToCombat")}
                  </button>
                  <button
                    type="button"
                    className="btn"
                    onClick={() => setTab("combat")}
                  >
                    <Plus size={15} />
                    {t("nav.combat")}
                  </button>
                </div>
              </div>
            </>
          ) : (
            <div className="empty">
              <Swords size={26} />
              <div className="font-medium text-[var(--text)]">
                {t("encounter.empty")}
              </div>
            </div>
          )}
        </section>
      </div>
    </div>
  );
}
